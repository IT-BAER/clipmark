# Builds src\Clipmark.Core\Emoji\Data from pinned Unicode / CLDR sources (pwsh 7):
#   emoji.tsv    group <TAB> emoji <TAB> English name, in Unicode order; fully-qualified, no skin tones, no components
#   <lang>.tsv   emoji <TAB> CLDR name <TAB> keywords joined by |, per UI language (emoji without CLDR data are left out)
# Sources: Unicode emoji-test.txt 18.0 and CLDR JSON 48.2.3 annotations (Unicode License v3).
$ErrorActionPreference = 'Stop'
$EmojiVersion = '18.0'
$CldrVersion = '48.2.3'
# UI language folder -> CLDR locale
$Locales = [ordered]@{
    'en' = 'en'; 'de' = 'de'; 'es' = 'es'; 'fr' = 'fr'; 'it' = 'it'; 'ja' = 'ja'; 'ko' = 'ko'; 'nl' = 'nl'; 'pl' = 'pl'
    'pt' = 'pt'; 'ru' = 'ru'; 'sv' = 'sv'; 'tr' = 'tr'; 'uk' = 'uk'; 'zh-Hans' = 'zh'; 'zh-Hant' = 'zh-Hant'
}
$root = Split-Path $PSScriptRoot -Parent
$out = Join-Path $root 'src\Clipmark.Core\Emoji\Data'
New-Item -ItemType Directory -Force $out | Out-Null
$utf8 = [Text.UTF8Encoding]::new($false)

function Get-Text([string]$url) { (Invoke-WebRequest $url -UseBasicParsing).Content }

$groups = @{
    'Smileys & Emotion' = 'smileys'; 'People & Body' = 'people'; 'Animals & Nature' = 'animals'; 'Food & Drink' = 'food'
    'Travel & Places' = 'travel'; 'Activities' = 'activities'; 'Objects' = 'objects'; 'Symbols' = 'symbols'; 'Flags' = 'flags'
}
$list = [Collections.Generic.List[string[]]]::new()
$group = $null
foreach ($line in (Get-Text "https://www.unicode.org/Public/$EmojiVersion.0/emoji/emoji-test.txt") -split "`n") {
    if ($line -match '^# group: (.+)$') { $group = $groups[$Matches[1].Trim()]; continue }
    if (-not $group -or $line -notmatch '^([0-9A-F ]+?)\s*; fully-qualified\s+# \S+ E[\d.]+ (.+)$') { continue }
    $cps = $Matches[1].Trim() -split ' '
    if ($cps | Where-Object { $_ -match '^1F3F[B-F]$' }) { continue } # skin tones
    $emoji = -join ($cps | ForEach-Object { [char]::ConvertFromUtf32([Convert]::ToInt32($_, 16)) })
    $list.Add(@($group, $emoji, $Matches[2].Trim()))
}
$header = "# Generated by scripts\gen-emoji.ps1 from Unicode emoji-test.txt $EmojiVersion and CLDR JSON $CldrVersion (Unicode License v3)."
[IO.File]::WriteAllLines((Join-Path $out 'emoji.tsv'), [string[]](@($header) + ($list | ForEach-Object { $_ -join "`t" })), $utf8)

$cldr = "https://raw.githubusercontent.com/unicode-org/cldr-json/$CldrVersion/cldr-json"
foreach ($lang in $Locales.Keys) {
    $loc = $Locales[$lang]
    $plain = (Get-Text "$cldr/cldr-annotations-full/annotations/$loc/annotations.json" | ConvertFrom-Json -AsHashtable).annotations.annotations
    $derived = (Get-Text "$cldr/cldr-annotations-derived-full/annotationsDerived/$loc/annotations.json" | ConvertFrom-Json -AsHashtable).annotationsDerived.annotations
    $lines = [Collections.Generic.List[string]]::new()
    $lines.Add($header)
    foreach ($e in $list) {
        $key = $e[1].Replace([string][char]0xFE0F, '')
        $a = if ($plain.ContainsKey($key)) { $plain[$key] } elseif ($derived.ContainsKey($key)) { $derived[$key] } else { $null }
        if (-not $a -or -not $a['tts']) { continue }
        $name = $a['tts'][0]
        $keywords = @($a['default'] | Where-Object { $_ -ne $name }) -join '|'
        $lines.Add("$($e[1])`t$name`t$keywords")
    }
    [IO.File]::WriteAllLines((Join-Path $out "$lang.tsv"), $lines, $utf8)
    "{0,-8} {1} emoji" -f $lang, ($lines.Count - 1)
}
"emoji.tsv $($list.Count) emoji"
